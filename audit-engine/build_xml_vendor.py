"""Generate the ESM wrapper from the exact, licensed upstream SAX source."""
import argparse,hashlib,pathlib
EXPECTED={'lib/sax.js':'1cdc1270d987cb0f6ee66dd8efb01c50511aa14d17b6163bbbffb21df8cf1c06','LICENSE.md':'8a1af140fdfbf5afd3df27f7e662f989c5b963a300020dfafce42033cae9e004'}
def build(source):
 files={n:(source/n).read_bytes() for n in EXPECTED}
 for n,b in files.items():
  if hashlib.sha256(b).hexdigest()!=EXPECTED[n]:raise ValueError('Upstream SAX source or license hash mismatch: '+n)
 target=pathlib.Path(__file__).resolve().parent/'vendor';target.mkdir(exist_ok=True)
 # Upstream's optional Node stream import is caught by its own browser fallback.
 # Only SAXParser is exported; no filesystem/stream interface is exposed.
 (target/'sax-1.6.1.mjs').write_bytes(b'// Generated by build_xml_vendor.py; upstream source is unchanged below.\nconst exports = {};\n'+files['lib/sax.js']+b'\nexport const SAXParser = exports.SAXParser;\n')
 (target/'SAX-LICENSE.md').write_bytes(files['LICENSE.md'])
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('source',type=pathlib.Path);a=p.parse_args();build(a.source)
